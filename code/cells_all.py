"""All supercells (HNF p,q,s) of the triangular lattice with N=pq<=NMAX, p,q>=3, reduced by the D6 point group.
Lattice basis a1=(1,0), a2=(1/2,sqrt3/2) in integer coords; HNF columns v1=(p,0), v2=(s,q)."""
import itertools, json, sys
from math import gcd
NMAX=int(sys.argv[1]) if len(sys.argv)>1 else 45
# D6 on integer coords (i,j) of triangular lattice: rotation by 60deg: (i,j)->(-j, i+j); reflection: (i,j)->(j,i)
R=((0,-1),(1,1)); F=((0,1),(1,0))
def mul(A,B): return tuple(tuple(sum(A[r][k]*B[k][c] for k in range(2)) for c in range(2)) for r in range(2))
G=[((1,0),(0,1))]
for _ in range(5): G.append(mul(R,G[-1]))
G+= [mul(F,g) for g in G]
def hnf(cols):
    # cols: two integer column vectors spanning sublattice; return canonical (p,s,q) with basis (p,0),(s,q)
    (a,b),(c,d)=cols
    # lattice generated by columns; compute HNF via row ops on matrix [[a,c],[b,d]] (rows=coords)
    # want lower form: vectors (p,0) and (s,q), q>0, 0<=s<p
    import math
    q=math.gcd(b,d); # second coordinate gcd
    # find vector with second coord q
    from itertools import product
    # extended gcd
    def eg(x,y):
        if y==0: return (x,1,0)
        g,u,v=eg(y,x%y); return (g,v,u-(x//y)*v)
    g,u,v=eg(b,d)
    if g<0: g,u,v=-g,-u,-v
    s=u*a+v*c; q=g
    N=abs(a*d-b*c); p=N//q
    return (p, s%p, q)
def apply(g,v): return (g[0][0]*v[0]+g[0][1]*v[1], g[1][0]*v[0]+g[1][1]*v[1])
seen={}; 
for N in range(9,NMAX+1):
    for q in range(1,N+1):
        if N%q: continue
        p=N//q
        for s in range(p):
            key=min(hnf((apply(g,(p,0)),apply(g,(s,q)))) for g in G)
            seen.setdefault(key,(p,s,q))
out=[]
for (p,s,q),orig in seen.items():
    # need p>=3,q>=3 for enum_nb (6 distinct neighbours); try equivalent representative satisfying that
    out.append(dict(p=p,q=q,s=s,N=p*q))
json.dump(out,open('/home/claude/k1/cells_D6.json','w'))
from collections import Counter
